-- Code-Nest SRE v2.5.0: immutable RCA evaluation cases and manual offline replay history.

CREATE TABLE IF NOT EXISTS `sre_rca_evaluation_case` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '评测用例ID',
    `incident_id` BIGINT NOT NULL COMMENT '来源事故ID',
    `source_run_id` BIGINT NOT NULL COMMENT '来源调查运行ID',
    `source_artifact_id` BIGINT NOT NULL COMMENT '来源脱敏artifact ID',
    `source_feedback_id` BIGINT NOT NULL COMMENT '来源人工反馈修订ID',
    `context_json` MEDIUMTEXT NOT NULL COMMENT '人工提升时冻结的脱敏模型上下文，不经API返回',
    `context_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '冻结上下文SHA-256',
    `context_length` INT UNSIGNED NOT NULL COMMENT '冻结上下文字符数，最大60000',
    `context_truncated` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '冻结上下文是否被裁剪',
    `baseline_report_json` MEDIUMTEXT NOT NULL COMMENT '提升时冻结的已脱敏基准RCA报告',
    `expected_conclusion` VARCHAR(2000) NULL COMMENT '指定反馈修订中的期望结论',
    `feedback_accuracy` VARCHAR(16) NOT NULL COMMENT '提升时的ACCURATE/PARTIAL/INACCURATE',
    `feedback_gap_type` VARCHAR(32) NULL COMMENT '提升时的主要缺口类型',
    `source_prompt_id` VARCHAR(128) NOT NULL COMMENT '来源运行Prompt ID',
    `source_schema_id` VARCHAR(255) NOT NULL COMMENT '来源运行结构化Schema ID',
    `source_provider` VARCHAR(64) NOT NULL COMMENT '来源运行AI提供商',
    `source_configured_model` VARCHAR(128) NULL COMMENT '来源运行配置模型',
    `source_actual_model` VARCHAR(128) NULL COMMENT '来源运行实际模型',
    `source_invocation_outcome` VARCHAR(32) NOT NULL COMMENT '来源运行模型调用结果',
    `promoted_by` BIGINT NOT NULL COMMENT '显式提升用例的管理员ID',
    `promoted_at` DATETIME NOT NULL COMMENT '用例冻结时间',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_sre_rca_eval_case_feedback` (`source_feedback_id`),
    KEY `idx_sre_rca_eval_case_incident_promoted` (`incident_id`, `promoted_at`),
    KEY `idx_sre_rca_eval_case_context_hash` (`context_sha256`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='SRE RCA不可变离线评测用例';

CREATE TABLE IF NOT EXISTS `sre_rca_evaluation_run` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '评测运行ID',
    `status` VARCHAR(16) NOT NULL COMMENT 'RUNNING/SUCCEEDED/DEGRADED/FAILED',
    `requested_case_id` BIGINT NULL COMMENT '指定单用例ID，为空表示回放当前全部用例',
    `requested_by` BIGINT NOT NULL COMMENT '手动发起评测的管理员ID',
    `case_count` INT UNSIGNED NOT NULL COMMENT '本次冻结选择的用例数，最大100',
    `completed_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已完成结果数',
    `passed_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '达到评分门槛的用例数',
    `failed_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '未达到评分门槛的用例数',
    `average_score` DECIMAL(6,2) NULL COMMENT '透明规则聚合平均分，0到100',
    `prompt_id` VARCHAR(128) NOT NULL COMMENT '本次回放Prompt ID',
    `schema_id` VARCHAR(255) NOT NULL COMMENT '本次回放结构化Schema ID',
    `provider` VARCHAR(64) NULL COMMENT '本次回放配置提供商',
    `configured_model` VARCHAR(128) NULL COMMENT '本次回放配置模型',
    `failure_code` VARCHAR(128) NULL COMMENT '受控运行失败码，不保存异常正文',
    `started_at` DATETIME NOT NULL COMMENT '开始时间',
    `completed_at` DATETIME NULL COMMENT '结束时间',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_sre_rca_eval_run_status_started` (`status`, `started_at`),
    KEY `idx_sre_rca_eval_run_case_started` (`requested_case_id`, `started_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='SRE RCA管理员手动离线评测运行';

CREATE TABLE IF NOT EXISTS `sre_rca_evaluation_result` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '单用例评测结果ID',
    `evaluation_run_id` BIGINT NOT NULL COMMENT '评测运行ID',
    `case_id` BIGINT NOT NULL COMMENT '不可变评测用例ID',
    `status` VARCHAR(16) NOT NULL COMMENT 'SUCCEEDED/DEGRADED/FAILED',
    `candidate_report_json` MEDIUMTEXT NULL COMMENT '本次回放产生的已校验候选RCA报告',
    `prompt_id` VARCHAR(128) NOT NULL COMMENT '本次结果Prompt ID',
    `schema_id` VARCHAR(255) NOT NULL COMMENT '本次结果结构化Schema ID',
    `provider` VARCHAR(64) NOT NULL COMMENT '本次结果AI提供商',
    `configured_model` VARCHAR(128) NULL COMMENT '本次结果配置模型',
    `actual_model` VARCHAR(128) NULL COMMENT '上游响应声明的实际模型',
    `invocation_outcome` VARCHAR(32) NOT NULL COMMENT '模型调用、降级或受控失败结果',
    `conclusion_similarity` DECIMAL(5,4) NOT NULL COMMENT '期望结论Dice相似度，0到1',
    `evidence_recall` DECIMAL(5,4) NOT NULL COMMENT '基准证据引用召回率，0到1',
    `severity_matched` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '严重度是否一致',
    `safety_compliant` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否满足只读安全契约',
    `total_score` DECIMAL(6,2) NOT NULL COMMENT '固定权重总分，0到100',
    `passed` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否达到70分且通过安全及模型成功门槛',
    `score_detail_json` TEXT NULL COMMENT '确定性分项评分说明JSON',
    `failure_code` VARCHAR(128) NULL COMMENT '受控单用例失败码，不保存异常正文',
    `started_at` DATETIME NOT NULL COMMENT '单用例开始时间',
    `completed_at` DATETIME NOT NULL COMMENT '单用例结束时间',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_sre_rca_eval_result_run_case` (`evaluation_run_id`, `case_id`),
    KEY `idx_sre_rca_eval_result_case_created` (`case_id`, `create_time`),
    KEY `idx_sre_rca_eval_result_passed_score` (`passed`, `total_score`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='SRE RCA离线评测单用例结果';
